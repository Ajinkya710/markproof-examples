"""
A Claude agent that marks the images it hands over, using the Markproof MCP
server (`npx markproof-mcp`) for an invisible watermark + signed C2PA manifest
(EU AI Act Article 50).

    pip install -r requirements.txt          # Python 3.10+, Node 18+ for npx
    export ANTHROPIC_API_KEY=...
    export MARKPROOF_API_KEY=lt_live_...     # https://markproof.co/dashboard
    python agent.py path/to/generated.png
"""

import asyncio
import os
import sys

from anthropic import AsyncAnthropic
from anthropic.lib.tools.mcp import async_mcp_tool
from mcp import ClientSession
from mcp.client.stdio import StdioServerParameters, stdio_client

SERVER = StdioServerParameters(
    command="npx",
    args=["-y", "markproof-mcp"],
    env={**os.environ, "MARKPROOF_API_KEY": os.environ["MARKPROOF_API_KEY"]},
)

PROMPT = """The image at {path} was generated by our app ("my-app", model "my-model-v1").
Before it's published: mark it with mark_file, then run verify_file on the marked copy
and tell me the watermark code, the verify URL, and whether both marks were found."""


async def main(path: str) -> None:
    client = AsyncAnthropic()
    async with stdio_client(SERVER) as (read, write):
        async with ClientSession(read, write) as mcp:
            await mcp.initialize()
            tools = (await mcp.list_tools()).tools  # mark_file, verify_file, get_asset

            runner = client.beta.messages.tool_runner(
                model="claude-opus-5-5",
                max_tokens=16000,
                tools=[async_mcp_tool(t, mcp) for t in tools],
                messages=[{"role": "user", "content": PROMPT.format(path=os.path.abspath(path))}],
            )
            async for message in runner:
                for block in message.content:
                    if block.type == "text":
                        print(block.text)
                    elif block.type == "tool_use":
                        print(f"→ {block.name}({block.input})")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: python agent.py <image>")
    asyncio.run(main(sys.argv[1]))
